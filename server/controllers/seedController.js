import Complaint from '../models/Complaint.js';
import User from '../models/User.js';
import Counter from '../models/Counter.js';
import Notice from '../models/Notice.js';

const generateRandomDate = (start, end) => {
  return new Date(start.getTime() + Math.random() * (end.getTime() - start.getTime()));
};

export const seedDatabase = async (req, res) => {
  try {
    // 1. Fetch a few resident users to assign complaints to
    const residents = await User.find({ role: 'resident' }).limit(5);
    
    if (residents.length === 0) {
      return res.status(400).json({ success: false, message: 'Need at least one resident user in the system to seed complaints.' });
    }

    const categories = ['Plumbing', 'Electrical', 'Elevator', 'Security', 'Cleaning', 'General Maintenance'];
    const priorities = ['Low', 'Medium', 'High'];
    
    const complaintsToInsert = [];
    
    // We want to generate ~40 complaints over the last 60 days
    const now = new Date();
    const sixtyDaysAgo = new Date();
    sixtyDaysAgo.setDate(now.getDate() - 60);

    let currentYear = now.getFullYear();

    for (let i = 0; i < 40; i++) {
      // Create intelligent hotspot data: Make 'Plumbing' in 'Block B' occur more frequently to trigger heuristics
      const resident = residents[Math.floor(Math.random() * residents.length)];
      
      let category = categories[Math.floor(Math.random() * categories.length)];
      // Inject deliberate bias for heuristics to detect "Recurring Issues"
      if (i % 5 === 0) category = 'Plumbing'; 
      if (i % 7 === 0) category = 'Elevator';

      const priority = priorities[Math.floor(Math.random() * priorities.length)];
      
      // Increment counter manually
      const counter = await Counter.findOneAndUpdate(
        { name: 'complaintNumber' },
        { $inc: { seq: 1 } },
        { new: true, upsert: true }
      );
      const seqStr = String(counter.seq).padStart(4, '0');
      const complaintNumber = `CMP-${currentYear}-${seqStr}`;

      const createdAt = generateRandomDate(sixtyDaysAgo, now);
      
      // Status determination
      const randStatus = Math.random();
      let status = 'Open';
      let resolvedAt = null;
      let updatedAt = new Date(createdAt.getTime() + 1000 * 60 * 60); // +1 hour
      
      if (randStatus > 0.4) {
        status = 'Resolved';
        // Add random resolution time between 1 and 7 days
        resolvedAt = new Date(createdAt.getTime() + (Math.random() * 6 + 1) * 24 * 60 * 60 * 1000);
        // Cap to now
        if (resolvedAt > now) resolvedAt = now;
        updatedAt = resolvedAt;
      } else if (randStatus > 0.2) {
        status = 'In Progress';
      }

      // Initial history
      const statusHistory = [{
        status: 'Open',
        changedBy: resident._id,
        changedByName: resident.name,
        changedByRole: 'resident',
        note: 'Complaint raised by resident via Demo Seeder',
        timestamp: createdAt
      }];

      if (status === 'In Progress' || status === 'Resolved') {
        statusHistory.push({
          status: 'In Progress',
          changedBy: req.user._id, // Admin
          changedByName: req.user.name,
          changedByRole: 'admin',
          note: 'Assigned staff to investigate.',
          timestamp: new Date(createdAt.getTime() + 2 * 60 * 60 * 1000) // 2 hours later
        });
      }

      if (status === 'Resolved') {
        statusHistory.push({
          status: 'Resolved',
          changedBy: req.user._id,
          changedByName: req.user.name,
          changedByRole: 'admin',
          note: 'Issue fixed and verified.',
          timestamp: resolvedAt
        });
      }

      complaintsToInsert.push({
        complaintNumber,
        title: `Demo Complaint: ${category} issue reported`,
        category,
        description: `This is an autogenerated demo complaint for ${category}. The resident reported this issue on ${createdAt.toLocaleDateString()}. It requires attention according to SLA guidelines.`,
        priority,
        status,
        resident: resident._id,
        createdAt,
        updatedAt,
        resolvedAt,
        statusHistory
      });
    }

    await Complaint.insertMany(complaintsToInsert);

    // 2. Seed a couple of notices
    await Notice.insertMany([
      {
        title: "Annual General Body Meeting",
        content: "Please join us for the AGM this Sunday. We will discuss the upcoming festival budget and maintenance updates.",
        category: "Meeting",
        isPinned: true,
        createdBy: req.user._id,
        createdAt: new Date(now.getTime() - 2 * 24 * 60 * 60 * 1000)
      },
      {
        title: "Water Supply Interruption",
        content: "Water supply will be cut off for 2 hours on Thursday afternoon for overhead tank cleaning. Please store water.",
        category: "Maintenance",
        isPinned: false,
        createdBy: req.user._id,
        createdAt: new Date(now.getTime() - 5 * 24 * 60 * 60 * 1000)
      }
    ]);

    res.json({
      success: true,
      message: 'Database seeded successfully with 40 realistic complaints and 2 notices! Operations Dashboard is now fully lit up.'
    });

  } catch (error) {
    console.error('[Seed Error]:', error);
    res.status(500).json({ success: false, message: error.message });
  }
};
